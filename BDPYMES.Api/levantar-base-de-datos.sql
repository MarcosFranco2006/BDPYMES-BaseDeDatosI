CREATE PROCEDURE [dbo].[SP_RegistrarTasaConValidacion]
    @IdInstrumento INT,
    @TasaInteres DECIMAL(6,3)
AS
BEGIN
    BEGIN TRANSACTION;
    BEGIN TRY
        IF NOT EXISTS (SELECT 1 FROM INSTRUMENTOS WHERE [ID-INSTRUMENTO] = @IdInstrumento)
        BEGIN
            RAISERROR('El instrumento especificado no existe.', 16, 1);
        END

        INSERT INTO [TAZA-DE-INTERES] ([ID-INSTRUMENTO], FechaUltimaActualizacion, TazaDeInteres)
        VALUES (@IdInstrumento, GETDATE(), @TasaInteres);
        COMMIT TRANSACTION;
        PRINT 'Transacción completada y guardada con éxito.';
    END TRY
    BEGIN CATCH 
        IF @@TRANCOUNT > 0
            ROLLBACK TRANSACTION;
        DECLARE @ErrorMessage NVARCHAR(4000) = ERROR_MESSAGE();
        RAISERROR(@ErrorMessage, 16, 1);
    END CATCH
END;
GO
